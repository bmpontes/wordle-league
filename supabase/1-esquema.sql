-- Validação de um valor inteiro (aceita número ou texto numérico).
create or replace function wl.v_int(v jsonb, p_min integer, p_max integer, p_label text) returns integer
language plpgsql immutable as $$
declare t text := v #>> '{}'; n numeric;
begin
  if jsonb_typeof(v) not in ('number', 'string') or t !~ '^\s*-?\d+(\.0+)?\s*$' then
    perform wl.fail('BAD_SETTING', format('"%s" deve ser um número inteiro entre %s e %s.', p_label, p_min, p_max), 400);
  end if;
  n := t::numeric;
  if n < p_min or n > p_max then
    perform wl.fail('BAD_SETTING', format('"%s" deve ser um número inteiro entre %s e %s.', p_label, p_min, p_max), 400);
  end if;
  return n::int;
end $$;

create or replace function wl.v_bool(v jsonb, p_key text) returns boolean language plpgsql immutable as $$
begin
  if jsonb_typeof(v) is distinct from 'boolean' then
    perform wl.fail('BAD_SETTING', format('"%s" deve ser verdadeiro ou falso.', p_key), 400);
  end if;
  return v::text::boolean;
end $$;

create or replace function wl.v_text(v jsonb, p_min integer, p_max integer, p_label text) returns text
language plpgsql immutable as $$
declare t text;
begin
  if jsonb_typeof(v) is distinct from 'string' then perform wl.fail('BAD_SETTING', format('Campo "%s" inválido.', p_label), 400); end if;
  t := btrim(v #>> '{}');
  if char_length(t) < p_min then perform wl.fail('BAD_SETTING', format('"%s" deve ter pelo menos %s caracteres.', p_label, p_min), 400); end if;
  if char_length(t) > p_max then perform wl.fail('BAD_SETTING', format('"%s" deve ter no máximo %s caracteres.', p_label, p_max), 400); end if;
  if not wl.safe_text(t) then perform wl.fail('BAD_SETTING', format('"%s" contém caracteres inválidos.', p_label), 400); end if;
  return t;
end $$;

-- Dias de jogo: lista de 1 (segunda) a 7 (domingo), sem repetições, com pelo menos um dia.
create or replace function wl.v_days(v jsonb) returns jsonb language plpgsql immutable as $$
declare out jsonb;
begin
  if jsonb_typeof(v) is distinct from 'array' or jsonb_array_length(v) = 0
     or exists (select 1 from jsonb_array_elements(v) e where jsonb_typeof(e) <> 'number' or e::text !~ '^[1-7]$') then
    perform wl.fail('BAD_SETTING', 'Escolha pelo menos um dia de jogo.', 400);
  end if;
  select jsonb_agg(d order by d) into out from (select distinct e::text::int as d from jsonb_array_elements(v) e) x;
  return out;
end $$;

create or replace function wl.v_int_array(v jsonb, p_min_len integer, p_max_len integer, p_label text, p_err text) returns jsonb
language plpgsql immutable as $$
declare out jsonb := '[]'::jsonb; i integer;
begin
  if jsonb_typeof(v) is distinct from 'array' or jsonb_array_length(v) < p_min_len or jsonb_array_length(v) > p_max_len then
    perform wl.fail('BAD_SETTING', p_err, 400);
  end if;
  for i in 0 .. jsonb_array_length(v) - 1 loop
    out := out || to_jsonb(wl.v_int(v->i, 0, 1000, format(p_label, i + 1)));
  end loop;
  return out;
end $$;

create or replace function public.admin_update_settings(p_changes jsonb) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  me wl.profiles := wl.me_admin();
  cur jsonb := wl.cfg();
  nxt jsonb := wl.cfg();
  changed jsonb := '{}'::jsonb;
  k text; v jsonb; nv jsonb;
begin
  if jsonb_typeof(p_changes) is distinct from 'object' then perform wl.fail('BAD_REQUEST', 'Corpo do pedido inválido.', 400); end if;
  for k, v in select * from jsonb_each(p_changes) loop
    nv := case k
      when 'word_length' then to_jsonb(wl.v_int(v, 3, 10, 'Tamanho das palavras'))
      when 'max_attempts' then to_jsonb(wl.v_int(v, 1, 10, 'Número de tentativas'))
      when 'points_by_attempt' then wl.v_int_array(v, 1, 10, 'Pontos (tentativa %s)', 'Tabela de pontos inválida.')
      when 'points_loss' then to_jsonb(wl.v_int(v, 0, 1000, 'Pontos por participação'))
      when 'streak_bonus_days' then to_jsonb(wl.v_int(v, 2, 365, 'Dias do bónus de streak'))
      when 'streak_bonus_points' then to_jsonb(wl.v_int(v, 0, 1000, 'Pontos do bónus de streak'))
      when 'podium_bonus_points' then wl.v_int_array(v, 0, 10, 'Bónus do %s.º a acertar', 'Bónus de pódio inválido (no máximo 10 posições).')
      when 'play_start' then to_jsonb(wl.v_text(v, 5, 5, 'Hora de abertura'))
      when 'play_end' then to_jsonb(wl.v_text(v, 5, 5, 'Hora de fecho'))
      when 'play_days' then wl.v_days(v)
      when 'streak_mode' then v
      when 'accent_mode' then v
      when 'registration_enabled' then to_jsonb(wl.v_bool(v, k))
      when 'recycle_words' then to_jsonb(wl.v_bool(v, k))
      when 'public_leaderboard' then to_jsonb(wl.v_bool(v, k))
      when 'brand_name' then to_jsonb(wl.v_text(v, 2, 40, 'Nome do jogo'))
      when 'brand_tagline' then to_jsonb(wl.v_text(v, 0, 60, 'Subtítulo'))
      when 'brand_footer' then to_jsonb(wl.v_text(v, 0, 120, 'Rodapé'))
      when 'brand_logo_round' then to_jsonb(wl.v_bool(v, k))
      else null end;
    if nv is null then perform wl.fail('BAD_SETTING', format('Parâmetro desconhecido: %s', k), 400); end if;
    if k in ('play_start', 'play_end') and nv #>> '{}' !~ '^([01]\d|2[0-3]):[0-5]\d$' then
      perform wl.fail('BAD_SETTING', format('"%s" contém caracteres inválidos.', case k when 'play_start' then 'Hora de abertura' else 'Hora de fecho' end), 400);
    end if;
    if k = 'streak_mode' and (jsonb_typeof(v) <> 'string' or v #>> '{}' not in ('wins', 'participation')) then
      perform wl.fail('BAD_SETTING', '"streak_mode" deve ser um de: wins, participation.', 400);
    end if;
    if k = 'accent_mode' and (jsonb_typeof(v) <> 'string' or v #>> '{}' not in ('strip', 'strict')) then
      perform wl.fail('BAD_SETTING', '"accent_mode" deve ser um de: strip, strict.', 400);
    end if;
    nxt := jsonb_set(nxt, array[k], nv);
    if nv <> cur->k then changed := changed || jsonb_build_object(k, jsonb_build_object('from', cur->k, 'to', nv)); end if;
  end loop;

  if wl.hhmm(nxt->>'play_start') >= wl.hhmm(nxt->>'play_end', true) then
    perform wl.fail('BAD_SETTING', 'A hora de abertura tem de ser anterior à hora de fecho (00:00 = meia-noite).', 400);
  end if;
  if jsonb_array_length(nxt->'points_by_attempt') <> (nxt->>'max_attempts')::int then
    perform wl.fail('BAD_SETTING', 'A tabela de pontos deve ter um valor por cada tentativa permitida.', 400);
  end if;

  for k in select jsonb_object_keys(changed) loop
    insert into wl.settings (key, value, updated_by, updated_at) values (k, nxt->k, me.id, now())
    on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now();
  end loop;
  if changed <> '{}'::jsonb then perform wl.audit(me.id, 'settings.update', null, changed); end if;
  return jsonb_build_object('settings', nxt, 'changed', changed);
end $$;

