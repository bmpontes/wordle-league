-- Importação (a análise do ficheiro é feita no browser; aqui volta-se a validar tudo).
create or replace function public.admin_import_words(p_list text, p_mode text, p_filename text, p_words text[],
                                                     p_invalid integer, p_duplicates integer, p_confirm_replace boolean)
returns jsonb language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  me wl.profiles := wl.me_admin();
  wlen integer := (wl.cfg()->>'word_length')::int;
  cur integer;
  imp bigint;
  bad text;
  n integer;
  total integer;
begin
  if p_list not in ('secret', 'accepted') then perform wl.fail('BAD_LIST', 'Tipo de lista inválido (secret ou accepted).', 400); end if;
  if p_mode not in ('replace', 'append') then perform wl.fail('BAD_MODE', 'Modo de importação inválido (replace ou append).', 400); end if;
  if p_words is null or cardinality(p_words) = 0 then perform wl.fail('EMPTY', 'O ficheiro não contém palavras válidas.', 400); end if;
  if cardinality(p_words) > 300000 then perform wl.fail('TOO_MANY', 'Demasiadas palavras (máximo 300000).', 400); end if;

  create temp table if not exists wl_import (word text primary key, plain text, len integer) on commit drop;
  truncate wl_import;
  insert into wl_import select distinct wl.to_display(w), wl.strip(wl.to_display(w)), char_length(wl.to_display(w))
    from unnest(p_words) w on conflict do nothing;
  select i.word into bad from wl_import i where not wl.valid_chars(i.word) or i.len <> wlen limit 1;
  if bad is not null then
    perform wl.fail('BAD_WORD', format('Palavra inválida: "%s" (só letras, com %s letras).', left(bad, 40), wlen), 400);
  end if;

  cur := case when p_list = 'secret' then (select count(*) from wl.word_bank) else (select count(*) from wl.accepted_words) end;
  if p_mode = 'replace' and cur > 0 and p_confirm_replace is not true then
    perform wl.fail('CONFIRM_REQUIRED', format('A lista atual tem %s palavras. Confirme explicitamente a substituição.', cur), 400);
  end if;

  insert into wl.word_imports (list_type, filename, mode, valid_count, invalid_count, duplicate_count, inserted_count, imported_by)
  values (p_list, left(coalesce(p_filename, ''), 200), p_mode, (select count(*) from wl_import),
          greatest(coalesce(p_invalid, 0), 0), greatest(coalesce(p_duplicates, 0), 0), 0, me.id)
  returning id into imp;

  if p_list = 'secret' then
    if p_mode = 'replace' then delete from wl.word_bank; end if;
    insert into wl.word_bank (word, word_plain, length, import_id) select word, plain, wl_import.len, imp from wl_import
    on conflict (word) do nothing;
    get diagnostics n = row_count;
    total := (select count(*) from wl.word_bank);
  else
    if p_mode = 'replace' then delete from wl.accepted_words; end if;
    insert into wl.accepted_words (word, word_plain, length, import_id) select word, plain, wl_import.len, imp from wl_import
    on conflict (word) do nothing;
    get diagnostics n = row_count;
    total := (select count(*) from wl.accepted_words);
  end if;
  update wl.word_imports set inserted_count = n where id = imp;
  perform wl.audit(me.id, 'words.import', p_list, jsonb_build_object('mode', p_mode, 'filename', p_filename,
          'valid', (select count(*) from wl_import), 'invalid', p_invalid, 'duplicates', p_duplicates, 'inserted', n, 'previous', cur));
  return jsonb_build_object('listType', p_list, 'mode', p_mode, 'inserted', n, 'total', total);
end $$;

create or replace function public.admin_export_words(p_list text) returns text
language plpgsql stable security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin();
begin
  if p_list = 'secret' then
    return coalesce((select string_agg(word, E'\n' order by word) from wl.word_bank), '') || E'\n';
  elsif p_list = 'accepted' then
    return coalesce((select string_agg(word, E'\n' order by word) from wl.accepted_words), '') || E'\n';
  end if;
  perform wl.fail('BAD_LIST', 'Tipo de lista inválido.', 400);
  return null;
end $$;

