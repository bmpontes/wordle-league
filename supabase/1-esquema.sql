end $$;

-- -----------------------------------------------------------------------------
-- Permissões das funções
-- -----------------------------------------------------------------------------

do $$
declare
  f record;
  public_fns text[] := array['get_brand', 'get_session', 'check_signup', 'public_leaderboard'];
  has_roles boolean := exists (select 1 from pg_roles where rolname = 'anon');
begin
  -- Funções internas: ninguém as chama diretamente.
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'wl' loop
    execute format('revoke all on function %s from public', f.sig);
    if has_roles then execute format('revoke all on function %s from anon, authenticated', f.sig); end if;
  end loop;

  -- Funções da app: só utilizadores com sessão, exceto as públicas.
  for f in
    select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.proname in (
       'get_brand', 'get_session', 'check_signup', 'touch_login', 'note_password_changed', 'is_admin',
       'get_game_state', 'submit_guess', 'leaderboard_daily', 'leaderboard_monthly', 'leaderboard_alltime',
       'leaderboard_seasons', 'public_leaderboard', 'get_profile', 'get_rules',
       'admin_status', 'admin_stats', 'admin_users', 'admin_prepare_user', 'admin_set_status', 'admin_reset_password',
       'admin_rename', 'admin_get_settings', 'admin_update_settings', 'admin_words', 'admin_words_existing',
       'admin_import_words', 'admin_export_words', 'admin_adjustments', 'admin_adjust_points', 'admin_audit',
       'admin_brand_set', 'admin_brand_remove')
  loop
    execute format('revoke all on function %s from public', f.sig);
    if has_roles then
      execute format('revoke all on function %s from anon, authenticated', f.sig);
      execute format('grant execute on function %s to authenticated', f.sig);
      if f.proname = any(public_fns) then execute format('grant execute on function %s to anon', f.sig); end if;
    end if;
  end loop;
end $$;

