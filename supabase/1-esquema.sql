-- Passo 1 da criação de uma conta pelo administrador: reserva o nome. A app faz
-- depois o registo no Supabase Auth, que é aceite mesmo com o registo público desligado.
create or replace function public.admin_prepare_user(p_username text, p_display_name text, p_role text) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin(); u text := lower(btrim(coalesce(p_username, ''))); dn text := btrim(coalesce(p_display_name, ''));
begin
  if u !~ '^[a-z0-9._-]{3,32}$' then
    perform wl.fail('BAD_USERNAME', 'O nome de utilizador deve ter 3 a 32 caracteres (letras minúsculas, números, ponto, hífen ou _).', 400);
  end if;
  if char_length(dn) not between 2 and 40 or not wl.safe_text(dn) then
    perform wl.fail('BAD_DISPLAY_NAME', 'O nome de apresentação deve ter 2 a 40 caracteres, sem < nem >.', 400);
  end if;
  if p_role not in ('user', 'admin') then perform wl.fail('BAD_ROLE', 'Perfil inválido.', 400); end if;
  if exists (select 1 from wl.profiles where username = u) then
    perform wl.fail('USERNAME_TAKEN', 'Esse nome de utilizador já existe.', 409);
  end if;
  insert into wl.pending_signups (username, display_name, role, created_by) values (u, dn, p_role, me.id)
  on conflict (username) do update set display_name = excluded.display_name, role = excluded.role,
                                       created_by = excluded.created_by, created_at = now();
  return jsonb_build_object('username', u);
end $$;

