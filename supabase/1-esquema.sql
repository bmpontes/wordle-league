-- Termina as sessões de uma conta no Supabase Auth (o bloqueio também é verificado
-- em todas as funções, por isso isto é apenas uma camada extra).
create or replace function wl.end_sessions(p_id uuid, p_ban boolean) returns void
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
begin
  begin
    update auth.users set banned_until = case when p_ban then 'infinity'::timestamptz else null end where id = p_id;
    delete from auth.sessions where user_id = p_id;
  exception when others then
    raise warning 'Não foi possível terminar as sessões: %', sqlerrm;
  end;
end $$;

create or replace function public.admin_set_status(p_id uuid, p_status text) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin(); u wl.profiles := wl.admin_target(p_id);
begin
  if p_status not in ('active', 'blocked') then perform wl.fail('BAD_STATUS', 'Estado inválido.', 400); end if;
  if u.id = me.id then perform wl.fail('SELF', 'Não pode bloquear a sua própria conta.', 400); end if;
  if p_status = 'blocked' and u.role = 'admin'
     and (select count(*) from wl.profiles where role = 'admin' and status = 'active') <= 1 then
    perform wl.fail('LAST_ADMIN', 'Não é possível bloquear o último administrador ativo.', 400);
  end if;
  update wl.profiles set status = p_status, updated_at = now() where id = u.id returning * into u;
  perform wl.end_sessions(u.id, p_status = 'blocked');
  perform wl.audit(me.id, case when p_status = 'blocked' then 'user.block' else 'user.unblock' end, u.username);
  return jsonb_build_object('user', wl.user_json(u));
end $$;

create or replace function public.admin_reset_password(p_id uuid, p_password text) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin(); u wl.profiles := wl.admin_target(p_id);
begin
  if p_password is null or char_length(p_password) < 10 then
    perform wl.fail('WEAK_PASSWORD', 'A password deve ter pelo menos 10 caracteres.', 400);
  end if;
  if char_length(p_password) > 72 then
    perform wl.fail('WEAK_PASSWORD', 'A password deve ter no máximo 72 caracteres.', 400);
  end if;
  if position(u.username in lower(p_password)) > 0 then
    perform wl.fail('WEAK_PASSWORD', 'A password não pode conter o nome de utilizador.', 400);
  end if;
  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf', 10)), updated_at = now()
   where id = u.id;
  perform wl.end_sessions(u.id, u.status = 'blocked');
  perform wl.audit(me.id, 'user.reset_password', u.username);
  return jsonb_build_object('ok', true);
end $$;

