create or replace function public.leaderboard_daily(p_date text default null) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me(); d date; mode text := wl.cfg()->>'streak_mode';
begin
  perform wl.finalize_expired();
  if p_date is null or p_date = '' then d := wl.today();
  elsif p_date !~ '^\d{4}-\d{2}-\d{2}$' then perform wl.fail('BAD_DATE', 'Data inválida.', 400);
  else
    begin d := p_date::date;
    exception when others then perform wl.fail('BAD_DATE', 'Data inválida.', 400);
    end;
  end if;
  if d > wl.today() then perform wl.fail('FUTURE_DATE', 'Não existem classificações para datas futuras.', 400); end if;

  return jsonb_build_object('type', 'daily', 'date', to_char(d, 'YYYY-MM-DD'), 'rows', coalesce((
    select jsonb_agg(jsonb_build_object(
             'position', pos, 'displayName', display_name, 'points', points,
             'wins', case when status = 'won' then 1 else 0 end,
             'successRate', case when status = 'won' then 100 else 0 end,
             'bestStreak', best, 'attempts', attempts_used, 'status', status,
             'isMe', user_id = me.id) order by pos)
      from (
        select x.*, row_number() over (order by points desc, (status = 'won') desc, attempts_used, finished_at) as pos
          from (
            select r.user_id, u.display_name, r.status, r.attempts_used, r.finished_at,
                   coalesce((select sum(p.points) from wl.point_transactions p
                              where p.result_id = r.id and p.type in ('game_result', 'streak_bonus', 'first_win_bonus')), 0) as points,
                   coalesce(bs.best, 0) as best
              from wl.daily_results r
              join wl.profiles u on u.id = r.user_id and u.status = 'active'
              join wl.daily_challenges c on c.id = r.challenge_id
              left join wl.best_streaks('0001-01-01', '9999-12-31', mode) bs on bs.user_id = r.user_id
             where c.challenge_date = d and r.status <> 'in_progress'
          ) x
      ) y), '[]'::jsonb));
end $$;

