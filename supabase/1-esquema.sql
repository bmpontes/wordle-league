create or replace function public.get_profile() returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  me wl.profiles := wl.me();
  s jsonb := wl.cfg();
  mode text := s->>'streak_mode';
  games integer; wins integer; maxatt integer;
  cur integer; best integer;
  best_rank jsonb;
begin
  perform wl.finalize_expired();
  select count(*), count(*) filter (where status = 'won') into games, wins
    from wl.daily_results where user_id = me.id and status <> 'in_progress';
  select greatest((s->>'max_attempts')::int, coalesce(max(c.max_attempts), 0)) into maxatt
    from wl.daily_results r join wl.daily_challenges c on c.id = r.challenge_id
   where r.user_id = me.id and r.status <> 'in_progress';
  cur := wl.current_streak(me.id, mode);
  select coalesce(max(bs.best), 0) into best from wl.best_streaks('0001-01-01', '9999-12-31', mode) bs where bs.user_id = me.id;

  select jsonb_build_object('position', b.pos, 'season', se.code) into best_rank
    from wl.seasons se
    cross join lateral wl.board(se.starts_on, se.ends_on, se.code) b
   where b.user_id = me.id and (b.games > 0 or b.points <> 0)
   order by b.pos, se.code desc
   limit 1;

  return jsonb_build_object(
    'user', jsonb_build_object('username', me.username, 'displayName', me.display_name, 'role', me.role, 'createdAt', me.created_at),
    'streakMode', mode,
    'games', games,
    'wins', wins,
    'winRate', case when games > 0 then (round(wins * 1000.0 / games) / 10)::float8 else 0 end,
    'distribution', (
      select jsonb_agg(jsonb_build_object('attempts', a, 'count',
               (select count(*) from wl.daily_results r where r.user_id = me.id and r.status = 'won' and r.attempts_used = a)) order by a)
        from generate_series(1, maxatt) a),
    'totalPoints', (select coalesce(sum(points), 0) from wl.point_transactions where user_id = me.id),
    'currentStreak', cur,
    'bestStreak', best,
    'bestMonthlyRank', best_rank,
    'history', coalesce((
      select jsonb_agg(h order by h->>'date' desc) from (
        select jsonb_build_object(
                 'date', to_char(c.challenge_date, 'YYYY-MM-DD'),
                 'word', c.word,  -- só desafios já concluídos por este utilizador
                 'status', r.status,
                 'attempts', r.attempts_used,
                 'points', coalesce((select sum(p.points) from wl.point_transactions p
                                      where p.result_id = r.id and p.type in ('game_result', 'streak_bonus', 'first_win_bonus')), 0),
                 'bonus', coalesce((select sum(p.points) from wl.point_transactions p
                                     where p.result_id = r.id and p.type in ('streak_bonus', 'first_win_bonus')), 0)) as h
          from wl.daily_results r join wl.daily_challenges c on c.id = r.challenge_id
         where r.user_id = me.id and r.status <> 'in_progress'
         order by c.challenge_date desc limit 365) x), '[]'::jsonb),
    'pointEvents', coalesce((
      select jsonb_agg(e order by id desc) from (
        select p.id, jsonb_build_object(
                 'type', p.type, 'points', p.points, 'reason', p.reason,
                 'date', to_char(c.challenge_date, 'YYYY-MM-DD'), 'season', se.code, 'createdAt', p.created_at) as e
          from wl.point_transactions p
          join wl.seasons se on se.id = p.season_id
          left join wl.daily_challenges c on c.id = p.challenge_id
         where p.user_id = me.id
         order by p.id desc limit 100) x), '[]'::jsonb)
  );
end $$;

