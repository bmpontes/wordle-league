-- Erro com código e "estado HTTP" para a app (message / hint = código / detail = estado).
create or replace function wl.fail(p_code text, p_message text, p_status integer default 400)
returns void language plpgsql as $$
begin
  raise exception using message = p_message, hint = p_code, detail = p_status::text, errcode = 'P0001';
end $$;

-- Hora atual (os testes podem fixá-la com: set wl.fake_now = '...').
create or replace function wl.now() returns timestamptz language sql stable as $$
  select coalesce(nullif(current_setting('wl.fake_now', true), '')::timestamptz, now())
$$;

-- Data de hoje em Portugal.
create or replace function wl.today() returns date language sql stable as $$
  select (wl.now() at time zone 'Europe/Lisbon')::date
$$;

-- "HH:MM" → minutos; com p_end_of_day, "00:00" significa meia-noite do fim do dia (1440).
create or replace function wl.hhmm(p text, p_end_of_day boolean default false) returns integer
language sql immutable as $$
  select case when p_end_of_day and split_part(p, ':', 1)::int * 60 + split_part(p, ':', 2)::int = 0 then 1440
              else split_part(p, ':', 1)::int * 60 + split_part(p, ':', 2)::int end
$$;

-- Instante correspondente a uma data + minutos, na hora de Portugal.
create or replace function wl.instant_at(p_date date, p_minutes integer) returns timestamptz
language sql stable as $$
  select (p_date::timestamp + make_interval(mins => p_minutes)) at time zone 'Europe/Lisbon'
$$;

create or replace function wl.iso(p timestamptz) returns text language sql stable as $$
  select to_char(p at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

create or replace function wl.season_code(p_date date) returns text language sql immutable as $$
  select to_char(p_date, 'YYYY-MM')
$$;

-- Remove acentos e cedilha (só existem estas letras acentuadas nas palavras válidas).
create or replace function wl.strip(p text) returns text language sql immutable as $$
  select translate(p, 'ÁÀÂÃÉÊÍÓÔÕÚÇ', 'AAAAEEIOOOUC')
$$;

-- Forma de apresentação: NFC, sem espaços envolventes, em maiúsculas.
create or replace function wl.to_display(p text) returns text language sql immutable as $$
  select upper(translate(normalize(regexp_replace(coalesce(p, ''), '^\s+|\s+$', '', 'g'), NFC),
                         'áàâãéêíóôõúç', 'ÁÀÂÃÉÊÍÓÔÕÚÇ'))
$$;

create or replace function wl.valid_chars(p text) returns boolean language sql immutable as $$
  select p ~ '^[A-ZÁÀÂÃÉÊÍÓÔÕÚÇ]+$'
$$;

-- Texto livre simples (nomes, motivos): sem caracteres de controlo nem < >.
create or replace function wl.safe_text(p text) returns boolean language sql immutable as $$
  select p !~ '[\x01-\x1f\x7f<>]'
$$;

create or replace function wl.audit(p_actor uuid, p_action text, p_target text default null, p_details jsonb default null)
returns void language sql as $$
  insert into wl.audit_log (actor_id, action, target, details) values (p_actor, p_action, p_target, p_details)
$$;

