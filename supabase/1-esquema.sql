create or replace function public.admin_brand_set(p_kind text, p_path text, p_mime text, p_size integer) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin(); old text;
begin
  if p_kind not in ('logo', 'ranking') then perform wl.fail('BAD_KIND', 'Tipo de imagem inválido (logo ou ranking).', 400); end if;
  if p_mime not in ('image/png', 'image/jpeg', 'image/webp') then
    perform wl.fail('BAD_TYPE', 'Formato não suportado. Use PNG, JPEG ou WEBP.', 400);
  end if;
  if p_size is null or p_size <= 0 or p_size > 2097152 then
    perform wl.fail('TOO_BIG', 'Imagem inválida ou demasiado grande (máximo 2 MB).', 400);
  end if;
  if p_path !~ ('^' || p_kind || '-[0-9a-z]+\.(png|jpg|webp)$') then perform wl.fail('BAD_PATH', 'Caminho inválido.', 400); end if;
  select path into old from wl.brand_assets where kind = p_kind;
  insert into wl.brand_assets (kind, path, mime, size, updated_by, updated_at) values (p_kind, p_path, p_mime, p_size, me.id, now())
  on conflict (kind) do update set path = excluded.path, mime = excluded.mime, size = excluded.size,
                                   updated_by = excluded.updated_by, updated_at = now();
  perform wl.audit(me.id, 'brand.upload', p_kind, jsonb_build_object('mime', p_mime, 'size', p_size));
  return public.get_brand() || jsonb_build_object('previousPath', old);
end $$;

create or replace function public.admin_brand_remove(p_kind text) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare me wl.profiles := wl.me_admin(); old text;
begin
  if p_kind not in ('logo', 'ranking') then perform wl.fail('BAD_KIND', 'Tipo de imagem inválido (logo ou ranking).', 400); end if;
