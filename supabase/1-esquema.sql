create or replace function wl.play_window() returns jsonb language plpgsql stable as $$
declare
  s jsonb := wl.cfg();
  t date := wl.today();
  local_ts timestamp := wl.now() at time zone 'Europe/Lisbon';
  mins integer := extract(hour from local_ts)::int * 60 + extract(minute from local_ts)::int;
  st integer := wl.hhmm(s->>'play_start');
  en integer := wl.hhmm(s->>'play_end', true);
  play_today boolean := wl.is_play_day(t, s);
  phase text;
  next_open date;
begin
  phase := case when not play_today then 'off' when mins < st then 'before' when mins >= en then 'after' else 'open' end;
  next_open := case when phase = 'before' then t else wl.next_play_day(t + 1, s) end;
  return jsonb_build_object(
    'open', phase = 'open',
    'phase', phase,
    'start', s->>'play_start',
    'end', s->>'play_end',
    'playDays', s->'play_days',
    'opensAt', wl.iso(wl.instant_at(next_open, st)),
    'closesAt', wl.iso(wl.instant_at(t, en)),
    -- "hoje", "amanhã", "na segunda-feira", "no sábado"…
    'nextOpenLabel', case when next_open = t then 'hoje' when next_open = t + 1 then 'amanhã'
                          when extract(isodow from next_open) >= 6 then 'no ' || wl.weekday_name(next_open)
                          else 'na ' || wl.weekday_name(next_open) end
  );
end $$;

create or replace function wl.closed_message(w jsonb) returns text language sql immutable as $$
  select case w->>'phase'
           when 'before' then format('O desafio de hoje abre às %s.', w->>'start')
           when 'off' then format('Hoje não há desafio. O próximo é %s, a partir das %s.', w->>'nextOpenLabel', w->>'start')
           else format('O desafio de hoje terminou às %s. Volte %s a partir das %s.', w->>'end', w->>'nextOpenLabel', w->>'start')
         end
$$;

create or replace function wl.build_state(ch wl.daily_challenges, res wl.daily_results, w jsonb) returns jsonb
language plpgsql stable as $$
declare base jsonb; st jsonb;
begin
  base := jsonb_build_object(
    'available', true,
    'window', w,
    'date', to_char(ch.challenge_date, 'YYYY-MM-DD'),
    'wordLength', ch.word_length,
    'maxAttempts', ch.max_attempts,
    'accentMode', ch.accent_mode,
    'nextChallengeAt', wl.iso(wl.instant_at(wl.next_play_day(wl.today() + 1), 0)),
    'serverNow', wl.iso(wl.now())
  );
  if res.id is null then
    return base || jsonb_build_object('status', 'not_started', 'guesses', '[]'::jsonb,
                                      'attemptsUsed', 0, 'attemptsLeft', ch.max_attempts);
  end if;
  st := base || jsonb_build_object(
    'status', res.status,
    'guesses', coalesce((select jsonb_agg(jsonb_build_object('word', g.guess, 'pattern', wl.pattern_names(g.pattern))
                                          order by g.attempt_number)
                           from wl.guesses g where g.result_id = res.id), '[]'::jsonb),
    'attemptsUsed', res.attempts_used,
    'attemptsLeft', greatest(0, ch.max_attempts - res.attempts_used)
  );
  if res.status <> 'in_progress' then
    st := st || (
      select jsonb_build_object(
        'points', coalesce(sum(p.points), 0),
        'bonus', coalesce(sum(p.points) filter (where p.type in ('streak_bonus', 'first_win_bonus')), 0),
        'bonuses', coalesce(jsonb_agg(jsonb_build_object('type', p.type, 'points', p.points, 'rank', p.win_rank, 'reason', p.reason)
                                      order by p.id) filter (where p.type in ('streak_bonus', 'first_win_bonus')), '[]'::jsonb),
        'solution', ch.word  -- só depois de o jogo deste utilizador terminar
      )
      from wl.point_transactions p
      where p.user_id = res.user_id and p.challenge_id = ch.id and p.type <> 'admin_adjustment'
    );
  end if;
  return st;
end $$;

create or replace function wl.unavailable_state(p_code text, p_message text, w jsonb) returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'available', false, 'window', w, 'code', p_code, 'message', p_message,
    'date', to_char(wl.today(), 'YYYY-MM-DD'),
    'nextChallengeAt', wl.iso(wl.instant_at(wl.next_play_day(wl.today() + 1), 0)),
    'serverNow', wl.iso(wl.now()))
$$;

-- Procura uma palavra numa lista segundo a política de acentos; devolve a forma da lista.
create or replace function wl.find_word(p_list text, p_display text, p_len integer, p_mode text) returns text
language plpgsql stable as $$
declare found_word text; plain text := wl.strip(p_display);
begin
  if p_list = 'accepted' then
    if p_mode = 'strict' then
      select word into found_word from wl.accepted_words where word = p_display and length = p_len;
    else
      select word into found_word from wl.accepted_words where word_plain = plain and length = p_len
       order by (word = p_display) desc, word collate "C" limit 1;
    end if;
  else
    if p_mode = 'strict' then
      select word into found_word from wl.word_bank where word = p_display and length = p_len;
    else
      select word into found_word from wl.word_bank where word_plain = plain and length = p_len
       order by (word = p_display) desc, word collate "C" limit 1;
    end if;
  end if;
  return found_word;
end $$;

