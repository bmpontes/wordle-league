create or replace function wl.ensure_season(p_code text) returns wl.seasons language plpgsql as $$
declare s wl.seasons; d date := (p_code || '-01')::date;
begin
  insert into wl.seasons (code, starts_on, ends_on)
  values (p_code, d, (d + interval '1 month' - interval '1 day')::date)
  on conflict (code) do nothing;
  select * into s from wl.seasons where code = p_code;
  return s;
end $$;

-- Escolha determinística e sem repetições (até esgotar): as candidatas com o tamanho
-- configurado são ordenadas por SHA-256(semente:ciclo:palavra); fica a primeira ainda
-- não usada. O desafio é guardado (único por data), por isso nunca muda depois de criado.
create or replace function wl.ensure_challenge(p_date date default null) returns wl.daily_challenges
language plpgsql as $$
declare
  d date := coalesce(p_date, wl.today());
  ch wl.daily_challenges;
  s jsonb;
  is_strict boolean;
  len integer;
  min_use integer;
  total integer;
  cyc integer;
  pick record;
  seed text;
begin
  select * into ch from wl.daily_challenges where challenge_date = d;
  if found then return ch; end if;

  perform pg_advisory_xact_lock(7337001);
  select * into ch from wl.daily_challenges where challenge_date = d;
  if found then return ch; end if;

  s := wl.cfg();
  is_strict := s->>'accent_mode' = 'strict';
  len := (s->>'word_length')::int;
  seed := wl.selection_seed();

  create temp table if not exists wl_pick (id bigint, word text, k text, n integer) on commit drop;
  truncate wl_pick;
  insert into wl_pick
  with cand as (
    select distinct on (k) id, word, k
      from (select id, word, case when is_strict then word else word_plain end as k
              from wl.word_bank where length = len) x
     order by k, word collate "C"
  ), used as (
    -- Só conta como usada uma palavra que alguém jogou: a de um dia sem jogadores
    -- volta a estar livre e, como a ordem é fixa, é a escolhida no dia de jogo seguinte.
    select case when is_strict then c.word else c.word_plain end as k, count(*)::int as n
      from wl.daily_challenges c
     where exists (select 1 from wl.daily_results r where r.challenge_id = c.id)
     group by 1
  )
  select c.id, c.word, c.k, coalesce(u.n, 0) from cand c left join used u on u.k = c.k;

  select min(n), count(*) into min_use, total from wl_pick;
  if total = 0 then
    perform wl.fail('NO_WORDS', 'Ainda não existe uma lista de palavras secretas importada. Contacte o administrador.', 503);
  end if;
  if min_use > 0 and not (s->>'recycle_words')::boolean then
    perform wl.fail('WORDS_EXHAUSTED', 'A lista de palavras secretas está esgotada. Contacte o administrador.', 503);
  end if;
  cyc := min_use + 1;

  select * into pick from wl_pick where n = min_use
   order by encode(extensions.digest(seed || ':' || cyc || ':' || k, 'sha256'), 'hex') collate "C"
   limit 1;

  insert into wl.daily_challenges
    (challenge_date, season_id, word_bank_id, word, word_plain, word_length, max_attempts, accent_mode, cycle)
  values
    (d, (wl.ensure_season(wl.season_code(d))).id, pick.id, pick.word, wl.strip(pick.word), len,
     (s->>'max_attempts')::int, s->>'accent_mode', cyc)
  returning * into ch;
  return ch;
end $$;

create or replace function wl.pool_status() returns jsonb language plpgsql as $$
declare
  s jsonb := wl.cfg();
  is_strict boolean := s->>'accent_mode' = 'strict';
  len integer := (s->>'word_length')::int;
  keys integer;
  unused integer;
begin
  with cand as (
    select distinct case when is_strict then word else word_plain end as k from wl.word_bank where length = len
  ), used as (
    select distinct case when is_strict then c.word else c.word_plain end as k from wl.daily_challenges c
     where exists (select 1 from wl.daily_results r where r.challenge_id = c.id)
  )
  select count(*), count(*) filter (where u.k is null) into keys, unused
    from cand c left join used u on u.k = c.k;
  return jsonb_build_object(
    'total', (select count(*) from wl.word_bank),
    'matchingLength', keys,
    'unused', unused,
    'exhausted', keys > 0 and unused = 0,
    'empty', keys = 0,
    'recycle', (s->>'recycle_words')::boolean,
    'daysLeft', unused
  );
end $$;

