-- Ninguém de fora acede às tabelas (só as funções abaixo, como "donas").
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'wl' loop
    execute format('alter table wl.%I enable row level security', t);
    execute format('revoke all on wl.%I from public', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on wl.%I from anon, authenticated', t);
    end if;
  end loop;
end $$;

-- -----------------------------------------------------------------------------
-- Regras de integridade: resultados, tentativas, pontos e auditoria não se apagam
