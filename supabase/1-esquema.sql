-- C = correta, P = presente noutra posição, A = ausente. Duas passagens, para tratar
-- corretamente as letras repetidas.
create or replace function wl.evaluate(p_guess text, p_secret text) returns text
language plpgsql immutable as $$
declare
  g text[] := regexp_split_to_array(p_guess, '');
  s text[] := regexp_split_to_array(p_secret, '');
  n integer := array_length(s, 1);
  res text[] := array_fill('A'::text, array[n]);
  used boolean[] := array_fill(false, array[n]);
  i integer; j integer;
begin
  if array_length(g, 1) is distinct from n then raise exception 'Tamanhos diferentes na avaliação.'; end if;
  for i in 1..n loop
    if g[i] = s[i] then res[i] := 'C'; used[i] := true; end if;
  end loop;
  for i in 1..n loop
    continue when res[i] = 'C';
    for j in 1..n loop
      if not used[j] and s[j] = g[i] then res[i] := 'P'; used[j] := true; exit; end if;
    end loop;
  end loop;
  return array_to_string(res, '');
end $$;

create or replace function wl.pattern_names(p text) returns jsonb language sql immutable as $$
  select coalesce(jsonb_agg(case c when 'C' then 'correct' when 'P' then 'present' else 'absent' end order by i), '[]'::jsonb)
    from regexp_split_to_table(p, '') with ordinality as t(c, i)
$$;

create or replace function wl.points_for(p_status text, p_attempts integer, s jsonb) returns integer
language sql immutable as $$
  select case when p_status = 'won'
              then (s->'points_by_attempt'->>(least(p_attempts, jsonb_array_length(s->'points_by_attempt')) - 1))::int
              else (s->>'points_loss')::int end
$$;

create or replace function wl.qualifies(p_status text, p_mode text) returns boolean language sql immutable as $$
  select case when p_mode = 'participation' then p_status in ('won', 'lost', 'expired') else p_status = 'won' end
$$;

-- Comprimento da streak que termina exatamente no dia de jogo p_date (0 se esse dia não
-- conta). Uma streak são dias de jogo seguidos (ver wl.game_days): fins de semana e dias
-- sem jogadores não a interrompem; um dia de jogo em que o utilizador não conta, sim.
create or replace function wl.streak_ending_at(p_user uuid, p_date date, p_mode text) returns integer
language plpgsql stable as $$
declare n integer := 0; d date;
begin
  for d in select g.d from wl.game_days() g where g.d <= p_date order by g.d desc loop
    exit when not exists (
      select 1 from wl.daily_results r join wl.daily_challenges c on c.id = r.challenge_id
       where r.user_id = p_user and c.challenge_date = d and wl.qualifies(r.status, p_mode));
    n := n + 1;
  end loop;
  return n;
end $$;

-- Streak atual: termina no último dia de jogo; se esse dia é hoje e o utilizador ainda
-- não jogou, termina no dia de jogo anterior (ainda pode jogar hoje sem a perder).
create or replace function wl.current_streak(p_user uuid, p_mode text) returns integer
language plpgsql stable as $$
declare last_day date; prev_day date; n integer;
begin
  select max(g.d) into last_day from wl.game_days() g where g.d <= wl.today();
  if last_day is null then return 0; end if;
  n := wl.streak_ending_at(p_user, last_day, p_mode);
  if n > 0 or last_day < wl.today() then return n; end if;
  select max(g.d) into prev_day from wl.game_days() g where g.d < last_day;
  return case when prev_day is null then 0 else wl.streak_ending_at(p_user, prev_day, p_mode) end;
end $$;

-- Melhor streak de cada utilizador num período (dias de jogo seguidos que contam).
create or replace function wl.best_streaks(p_from date, p_to date, p_mode text)
returns table (user_id uuid, best integer) language sql stable as $$
  with gd as (select * from wl.game_days()),
  q as (
    select distinct r.user_id, gd.n
      from wl.daily_results r
      join wl.daily_challenges c on c.id = r.challenge_id
      join gd on gd.d = c.challenge_date
     where c.challenge_date between p_from and p_to and wl.qualifies(r.status, p_mode)
  ), g as (
    select q.user_id, q.n - (row_number() over (partition by q.user_id order by q.n))::int as grp from q
  )
  select g.user_id, max(cnt)::int from (select g.user_id, g.grp, count(*) as cnt from g group by 1, 2) g group by 1
$$;

-- Atribuição de pontos ao concluir um jogo. Os índices únicos parciais impedem
-- pontos a dobrar mesmo em pedidos repetidos.
create or replace function wl.award(p_result wl.daily_results, p_challenge wl.daily_challenges, p_status text, p_attempts integer)
returns void language plpgsql as $$
declare
  s jsonb := wl.cfg();
  pts integer := wl.points_for(p_status, p_attempts, s);
  label text;
  inserted integer;
  streak integer;
  v_rank integer;
  bonus integer;
begin
  label := case p_status when 'won' then format('Vitória em %s tentativa(s)', p_attempts)
                         when 'expired' then 'Participação (jogo não concluído)'
                         else 'Participação sem vitória' end;
  insert into wl.point_transactions (user_id, season_id, challenge_id, result_id, type, points, reason)
  values (p_result.user_id, p_challenge.season_id, p_challenge.id, p_result.id, 'game_result', pts,
          format('%s — desafio de %s', label, to_char(p_challenge.challenge_date, 'YYYY-MM-DD')))
  on conflict do nothing;
  get diagnostics inserted = row_count;
  if inserted = 0 then return; end if;

  -- Bónus de streak (aos 7, 14, 21… dias, por omissão).
  if wl.qualifies(p_status, s->>'streak_mode') and (s->>'streak_bonus_points')::int > 0 then
    streak := wl.streak_ending_at(p_result.user_id, p_challenge.challenge_date, s->>'streak_mode');
    if streak > 0 and streak % (s->>'streak_bonus_days')::int = 0 then
      insert into wl.point_transactions (user_id, season_id, challenge_id, result_id, type, points, streak_length, reason)
      values (p_result.user_id, p_challenge.season_id, p_challenge.id, p_result.id, 'streak_bonus',
              (s->>'streak_bonus_points')::int, streak, format('Bónus de streak: %s dias consecutivos', streak))
      on conflict do nothing;
    end if;
  end if;

  -- Bónus de pódio: 1.º, 2.º, 3.º… a acertar. O desafio fica bloqueado durante a
  -- contagem, para dois vencedores simultâneos não ficarem com a mesma posição.
  if p_status = 'won' then
    perform 1 from wl.daily_challenges where id = p_challenge.id for update;
    select count(*) into v_rank from wl.daily_results where challenge_id = p_challenge.id and status = 'won';
    bonus := coalesce((s->'podium_bonus_points'->>(v_rank - 1))::int, 0);
    if bonus > 0 and v_rank <= 10 then
      insert into wl.point_transactions (user_id, season_id, challenge_id, result_id, type, points, win_rank, reason)
      values (p_result.user_id, p_challenge.season_id, p_challenge.id, p_result.id, 'first_win_bonus', bonus, v_rank,
              format('Bónus: %s.º a acertar no desafio de %s', v_rank, to_char(p_challenge.challenge_date, 'YYYY-MM-DD')))
      on conflict do nothing;
    end if;
  end if;
end $$;

-- Jogos começados em dias anteriores e não terminados passam a "expired" e recebem
-- os pontos de participação. É chamado antes de qualquer leitura de resultados.
create or replace function wl.finalize_expired() returns integer language plpgsql as $$
declare r wl.daily_results; ch wl.daily_challenges; n integer := 0; s jsonb := wl.cfg();
begin
  for r in
    select dr.* from wl.daily_results dr join wl.daily_challenges c on c.id = dr.challenge_id
     where dr.status = 'in_progress' and c.challenge_date < wl.today()
     for update of dr skip locked
  loop
    update wl.daily_results
       set status = 'expired', points = wl.points_for('expired', r.attempts_used, s), finished_at = wl.now()
     where id = r.id and status = 'in_progress';
    if found then
      select * into ch from wl.daily_challenges where id = r.challenge_id;
      perform wl.award(r, ch, 'expired', r.attempts_used);
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;

