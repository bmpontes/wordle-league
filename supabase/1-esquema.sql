-- Perfil de cada conta (o login é feito pelo Supabase Auth; o email é interno).
create table if not exists wl.profiles (
  id             uuid primary key references auth.users(id) on delete cascade,
  username       text not null unique check (username ~ '^[a-z0-9._-]{3,32}$'),
  display_name   text not null check (char_length(display_name) between 2 and 40),
  role           text not null default 'user' check (role in ('user', 'admin')),
  status         text not null default 'active' check (status in ('active', 'blocked')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  last_login_at  timestamptz
);

-- Contas criadas pelo administrador ficam aqui à espera de serem registadas
-- (permite criar contas mesmo com o registo público desligado).
create table if not exists wl.pending_signups (
  username      text primary key,
  display_name  text not null,
  role          text not null check (role in ('user', 'admin')),
  created_by    uuid references wl.profiles(id),
  created_at    timestamptz not null default now()
);

-- Parâmetros do jogo (valores JSON). Os valores por omissão estão em wl.defaults().
create table if not exists wl.settings (
  key         text primary key,
  value       jsonb not null,
  updated_at  timestamptz not null default now(),
  updated_by  uuid references wl.profiles(id)
);

create table if not exists wl.word_imports (
  id               bigint generated by default as identity primary key,
  list_type        text not null check (list_type in ('secret', 'accepted')),
  filename         text,
  mode             text not null check (mode in ('replace', 'append')),
  valid_count      integer not null,
  invalid_count    integer not null,
  duplicate_count  integer not null,
  inserted_count   integer not null,
  imported_by      uuid not null references wl.profiles(id),
  imported_at      timestamptz not null default now()
);

-- Palavras secretas (candidatas a palavra do dia).
create table if not exists wl.word_bank (
  id          bigint generated by default as identity primary key,
  word        text not null unique,   -- forma de apresentação (NFC, maiúsculas)
  word_plain  text not null,          -- sem acentos
  length      integer not null check (length > 0),
  import_id   bigint references wl.word_imports(id),
  created_at  timestamptz not null default now()
);
create index if not exists idx_word_bank_plain on wl.word_bank(word_plain);
create index if not exists idx_word_bank_length on wl.word_bank(length);

-- Palavras aceites nas tentativas (lista de validação).
create table if not exists wl.accepted_words (
  id          bigint generated by default as identity primary key,
  word        text not null unique,
  word_plain  text not null,
  length      integer not null check (length > 0),
  import_id   bigint references wl.word_imports(id),
  created_at  timestamptz not null default now()
);
create index if not exists idx_accepted_plain on wl.accepted_words(word_plain);

-- Épocas mensais.
create table if not exists wl.seasons (
  id          bigint generated by default as identity primary key,
  code        text not null unique check (code ~ '^\d{4}-\d{2}$'),
  starts_on   date not null,
  ends_on     date not null,
  created_at  timestamptz not null default now()
);

-- Um desafio por data. A palavra é copiada, para o histórico não depender da lista.
create table if not exists wl.daily_challenges (
  id              bigint generated by default as identity primary key,
  challenge_date  date not null unique,
  season_id       bigint not null references wl.seasons(id),
  word_bank_id    bigint references wl.word_bank(id) on delete set null,
  word            text not null,
  word_plain      text not null,
  word_length     integer not null check (word_length > 0),
  max_attempts    integer not null check (max_attempts between 1 and 10),
  accent_mode     text not null check (accent_mode in ('strip', 'strict')),
  cycle           integer not null default 1,
  created_at      timestamptz not null default now()
);
create index if not exists idx_challenges_season on wl.daily_challenges(season_id);

create table if not exists wl.daily_results (
  id             bigint generated by default as identity primary key,
  challenge_id   bigint not null references wl.daily_challenges(id),
  user_id        uuid not null references wl.profiles(id),
  status         text not null default 'in_progress' check (status in ('in_progress', 'won', 'lost', 'expired')),
  attempts_used  integer not null default 0 check (attempts_used >= 0),
  points         integer not null default 0,
  started_at     timestamptz not null default now(),
  finished_at    timestamptz,
  unique (challenge_id, user_id),
  check ((status = 'in_progress') = (finished_at is null))
);
create index if not exists idx_results_user on wl.daily_results(user_id);
create index if not exists idx_results_status on wl.daily_results(status);

create table if not exists wl.guesses (
  id              bigint generated by default as identity primary key,
  result_id       bigint not null references wl.daily_results(id),
  challenge_id    bigint not null references wl.daily_challenges(id),
  user_id         uuid not null references wl.profiles(id),
  attempt_number  integer not null check (attempt_number between 1 and 10),
  guess           text not null,
  pattern         text not null check (pattern ~ '^[CPA]+$'),  -- C=correta, P=presente, A=ausente
  created_at      timestamptz not null default now(),
  unique (result_id, attempt_number)
);

-- Livro de pontos: cada ponto tem um evento de origem; só se acrescenta.
create table if not exists wl.point_transactions (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references wl.profiles(id),
  season_id      bigint not null references wl.seasons(id),
  challenge_id   bigint references wl.daily_challenges(id),
  result_id      bigint references wl.daily_results(id),
  type           text not null check (type in ('game_result', 'streak_bonus', 'first_win_bonus', 'admin_adjustment')),
  points         integer not null,
  streak_length  integer,
  win_rank       integer check (win_rank is null or win_rank between 1 and 10),
  reason         text not null,
  created_by     uuid references wl.profiles(id),
  created_at     timestamptz not null default now(),
  check (type = 'admin_adjustment' or challenge_id is not null),
  check (type <> 'admin_adjustment' or created_by is not null)
);
create unique index if not exists uq_points_game_result on wl.point_transactions(user_id, challenge_id) where type = 'game_result';
create unique index if not exists uq_points_streak_bonus on wl.point_transactions(user_id, challenge_id) where type = 'streak_bonus';
create unique index if not exists uq_points_win_rank on wl.point_transactions(challenge_id, win_rank) where type = 'first_win_bonus';
create unique index if not exists uq_points_win_bonus_user on wl.point_transactions(user_id, challenge_id) where type = 'first_win_bonus';
create index if not exists idx_points_user on wl.point_transactions(user_id);
create index if not exists idx_points_season on wl.point_transactions(season_id);

create table if not exists wl.audit_log (
  id          bigint generated by default as identity primary key,
  actor_id    uuid references wl.profiles(id),
  action      text not null,
  target      text,
  details     jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists idx_audit_created on wl.audit_log(created_at);

