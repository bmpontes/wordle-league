create or replace function public.get_game_state() returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  me wl.profiles := wl.me();
  w jsonb;
  ch wl.daily_challenges;
  res wl.daily_results;
  err_code text;
  err_msg text;
begin
  perform wl.finalize_expired();
  w := wl.play_window();
  if not (w->>'open')::boolean then
    -- Fora do período: mostra o jogo de hoje se já o tiver começado.
    select * into ch from wl.daily_challenges where challenge_date = wl.today();
    if found then
      select * into res from wl.daily_results where challenge_id = ch.id and user_id = me.id;
      if found then return wl.build_state(ch, res, w); end if;
    end if;
    return wl.unavailable_state('CLOSED', wl.closed_message(w), w);
  end if;
  begin
    ch := wl.ensure_challenge();
  exception when sqlstate 'P0001' then
    get stacked diagnostics err_code = pg_exception_hint, err_msg = message_text;
    if err_code in ('NO_WORDS', 'WORDS_EXHAUSTED') then return wl.unavailable_state(err_code, err_msg, w); end if;
    raise;
  end;
  select * into res from wl.daily_results where challenge_id = ch.id and user_id = me.id;
  return wl.build_state(ch, res, w);
end $$;

create or replace function public.submit_guess(p_guess text) returns jsonb
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  me wl.profiles := wl.me();
  w jsonb;
  ch wl.daily_challenges;
  res wl.daily_results;
  display text;
  found_word text;
  key text;
  secret text;
  attempt integer;
  pat text;
  st text;
begin
  perform wl.finalize_expired();
  w := wl.play_window();
  if not (w->>'open')::boolean then perform wl.fail('CLOSED', wl.closed_message(w), 409); end if;
  ch := wl.ensure_challenge();

  select * into res from wl.daily_results where challenge_id = ch.id and user_id = me.id;
  if found and res.status <> 'in_progress' then
    perform wl.fail('GAME_OVER', 'O jogo de hoje já terminou. Volte amanhã!', 409);
  end if;

  -- Validação: uma palavra inválida NÃO gasta tentativa.
  if p_guess is null or char_length(p_guess) > 64 then perform wl.fail('BAD_REQUEST', 'Tentativa inválida.', 400); end if;
  display := wl.to_display(p_guess);
  if display = '' then perform wl.fail('EMPTY_GUESS', 'Escreva uma palavra.', 422); end if;
  if not wl.valid_chars(display) then
    perform wl.fail('INVALID_CHARACTERS', 'A palavra contém caracteres não permitidos.', 422);
  end if;
  if char_length(display) <> ch.word_length then
    perform wl.fail('WRONG_LENGTH', format('A palavra deve ter %s letras.', ch.word_length), 422);
  end if;
  -- As palavras secretas são sempre aceites como tentativa.
  found_word := coalesce(wl.find_word('accepted', display, ch.word_length, ch.accent_mode),
                         wl.find_word('secret', display, ch.word_length, ch.accent_mode));
  if found_word is null then perform wl.fail('WORD_NOT_ACCEPTED', 'Palavra não reconhecida.', 422); end if;
  key := case when ch.accent_mode = 'strict' then found_word else wl.strip(found_word) end;
  secret := case when ch.accent_mode = 'strict' then ch.word else ch.word_plain end;

  insert into wl.daily_results (challenge_id, user_id, started_at) values (ch.id, me.id, wl.now())
  on conflict (challenge_id, user_id) do nothing;
  select * into res from wl.daily_results where challenge_id = ch.id and user_id = me.id for update;
  if res.status <> 'in_progress' then perform wl.fail('GAME_OVER', 'O jogo de hoje já terminou. Volte amanhã!', 409); end if;
  attempt := res.attempts_used + 1;
  if attempt > ch.max_attempts then perform wl.fail('NO_ATTEMPTS_LEFT', 'Sem tentativas disponíveis.', 409); end if;

  pat := wl.evaluate(key, secret);
  insert into wl.guesses (result_id, challenge_id, user_id, attempt_number, guess, pattern, created_at)
  values (res.id, ch.id, me.id, attempt, found_word, pat, wl.now());
  update wl.daily_results set attempts_used = attempt where id = res.id returning * into res;

  if pat ~ '^C+$' or attempt = ch.max_attempts then
    st := case when pat ~ '^C+$' then 'won' else 'lost' end;
    update wl.daily_results set status = st, points = wl.points_for(st, attempt, wl.cfg()), finished_at = wl.now()
     where id = res.id returning * into res;
    perform wl.award(res, ch, st, attempt);
  end if;

  return wl.build_state(ch, res, w) || jsonb_build_object('lastPattern', wl.pattern_names(pat));
end $$;

