create or replace function wl.trg_forbid() returns trigger language plpgsql as $$
begin
  raise exception '%', tg_argv[0];
end $$;

create or replace function wl.trg_results_immutable() returns trigger language plpgsql as $$
begin
  if old.status <> 'in_progress' then
    raise exception 'Resultado concluído não pode ser alterado.';
  end if;
  return new;
end $$;

drop trigger if exists trg_results_immutable_when_finished on wl.daily_results;
create trigger trg_results_immutable_when_finished before update on wl.daily_results
  for each row execute function wl.trg_results_immutable();
drop trigger if exists trg_results_no_delete on wl.daily_results;
create trigger trg_results_no_delete before delete on wl.daily_results
  for each row execute function wl.trg_forbid('Resultados não podem ser apagados.');
drop trigger if exists trg_guesses_append_only on wl.guesses;
create trigger trg_guesses_append_only before update or delete on wl.guesses
  for each row execute function wl.trg_forbid('Tentativas não podem ser alteradas nem apagadas.');
drop trigger if exists trg_points_append_only on wl.point_transactions;
create trigger trg_points_append_only before update or delete on wl.point_transactions
  for each row execute function wl.trg_forbid('Movimentos de pontos não podem ser alterados nem apagados.');
drop trigger if exists trg_audit_append_only on wl.audit_log;
create trigger trg_audit_append_only before update or delete on wl.audit_log
  for each row execute function wl.trg_forbid('Registos de auditoria não podem ser alterados nem apagados.');

