-- =============================================================================
-- Wordle League — base de dados (Supabase / PostgreSQL)
--
-- Como usar: Supabase → SQL Editor → New query → colar TODO este ficheiro → Run.
-- Pode ser executado de novo sem perder dados (para aplicar atualizações).
--
-- Organização:
--  * As tabelas ficam no esquema privado "wl", que NÃO é exposto pela API do
--    Supabase. Nenhum browser lhes consegue aceder diretamente.
--  * A app só chama as funções do esquema "public" (RPC). São elas que validam,
--    avaliam as tentativas e atribuem pontos — tal como fazia o servidor Node.js.
--  * A palavra secreta nunca sai da base de dados antes de o jogador terminar.
-- =============================================================================

create extension if not exists pgcrypto with schema extensions;

create schema if not exists wl;
revoke all on schema wl from public;

