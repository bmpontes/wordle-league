  me wl.profiles := wl.me_admin();
  pool jsonb := wl.pool_status();
  ch wl.daily_challenges;
  warnings text[] := '{}';
  n_acc integer := (select count(*) from wl.accepted_words);
begin
  perform wl.finalize_expired();
  select * into ch from wl.daily_challenges where challenge_date = wl.today();
  if (pool->>'empty')::boolean then
