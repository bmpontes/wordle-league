-- Verificação antes do registo (mensagens claras; o trigger volta a validar tudo).
create or replace function public.check_signup(p_username text, p_display_name text) returns jsonb
language plpgsql stable security definer set search_path = wl, extensions, pg_temp as $$
declare u text := lower(btrim(coalesce(p_username, ''))); dn text := btrim(coalesce(p_display_name, ''));
begin
  if not (wl.cfg()->>'registration_enabled')::boolean and exists (select 1 from wl.profiles) then
    perform wl.fail('REGISTRATION_DISABLED', 'O registo de novas contas está desativado.', 403);
  end if;
  if u !~ '^[a-z0-9._-]{3,32}$' then
    perform wl.fail('BAD_USERNAME', 'O nome de utilizador deve ter 3 a 32 caracteres (letras minúsculas, números, ponto, hífen ou _).', 400);
  end if;
  if char_length(dn) not between 2 and 40 or not wl.safe_text(dn) then
    perform wl.fail('BAD_DISPLAY_NAME', 'O nome de apresentação deve ter 2 a 40 caracteres, sem < nem >.', 400);
  end if;
  if exists (select 1 from wl.profiles where username = u) then
    perform wl.fail('USERNAME_TAKEN', 'Esse nome de utilizador já existe.', 409);
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- Cria o perfil quando o Supabase Auth regista uma conta. O nome de utilizador é a
-- parte antes de "@" do email interno. A primeira conta criada fica administradora.
create or replace function wl.on_auth_user_created() returns trigger
language plpgsql security definer set search_path = wl, extensions, pg_temp as $$
declare
  u text := lower(split_part(new.email, '@', 1));
  dn text := btrim(coalesce(new.raw_user_meta_data->>'display_name', ''));
  pend wl.pending_signups;
  r text := 'user';
begin
  if u !~ '^[a-z0-9._-]{3,32}$' then raise exception 'Nome de utilizador inválido.'; end if;
  if dn = '' then dn := u; end if;
  if char_length(dn) not between 2 and 40 or not wl.safe_text(dn) then raise exception 'Nome de apresentação inválido.'; end if;

  select * into pend from wl.pending_signups where username = u and created_at > now() - interval '1 hour';
  if found then
    r := pend.role;
    dn := pend.display_name;
    delete from wl.pending_signups where username = u;
  elsif exists (select 1 from wl.profiles) and not (wl.cfg()->>'registration_enabled')::boolean then
    raise exception 'O registo de novas contas está desativado.';
  end if;
  if not exists (select 1 from wl.profiles where role = 'admin' and status = 'active') then
    r := 'admin';  -- primeira conta: administrador
  end if;

  insert into wl.profiles (id, username, display_name, role) values (new.id, u, dn, r);
  if pend.username is not null then
    perform wl.audit(pend.created_by, 'user.create', u, jsonb_build_object('role', r));
  else
    perform wl.audit(new.id, case when r = 'admin' then 'admin.bootstrap' else 'user.register' end, u);
  end if;
  return new;
end $$;

drop trigger if exists wl_on_auth_user_created on auth.users;
create trigger wl_on_auth_user_created after insert on auth.users
  for each row execute function wl.on_auth_user_created();

