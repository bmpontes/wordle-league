-- Classificação agregada (mensal se p_season for indicado, senão desde sempre).
create or replace function wl.board(p_from date, p_to date, p_season text)
returns table (user_id uuid, display_name text, points bigint, games bigint, wins bigint,
               success_rate double precision, best_streak integer, pos integer)
language sql stable as $$
  with pts as (
    select p.user_id, sum(p.points) as points
      from wl.point_transactions p join wl.seasons s on s.id = p.season_id
     where p_season is null or s.code = p_season
     group by p.user_id
  ), fin as (
    select r.user_id, count(*) as games, count(*) filter (where r.status = 'won') as wins
      from wl.daily_results r join wl.daily_challenges c on c.id = r.challenge_id
     where r.status <> 'in_progress' and c.challenge_date between p_from and p_to
     group by r.user_id
  ), ids as (select pts.user_id from pts union select fin.user_id from fin),
  rows as (
    select u.id as user_id, u.display_name,
           coalesce(pts.points, 0) as points,
           coalesce(fin.games, 0) as games,
           coalesce(fin.wins, 0) as wins,
           case when coalesce(fin.games, 0) > 0 then (round(fin.wins * 1000.0 / fin.games) / 10)::float8 else 0 end as success_rate,
           coalesce(bs.best, 0) as best_streak
      from ids
      join wl.profiles u on u.id = ids.user_id and u.status = 'active'
      left join pts on pts.user_id = ids.user_id
      left join fin on fin.user_id = ids.user_id
      left join wl.best_streaks(p_from, p_to, wl.cfg()->>'streak_mode') bs on bs.user_id = ids.user_id
  )
  select rows.*, (row_number() over (order by points desc, wins desc, success_rate desc, display_name))::int as pos
    from rows
   order by pos
$$;

create or replace function wl.board_json(p_from date, p_to date, p_season text, p_viewer uuid) returns jsonb
language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'position', b.pos, 'displayName', b.display_name, 'points', b.points, 'games', b.games,
           'wins', b.wins, 'successRate', b.success_rate, 'bestStreak', b.best_streak,
           'isMe', b.user_id = p_viewer) order by b.pos), '[]'::jsonb)
    from wl.board(p_from, p_to, p_season) b
$$;

