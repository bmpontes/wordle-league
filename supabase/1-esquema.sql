-- Perfil ativo de quem está a fazer o pedido (erro 401 se não houver).
create or replace function wl.me() returns wl.profiles language plpgsql stable as $$
declare p wl.profiles;
begin
  select * into p from wl.profiles where id = auth.uid() and status = 'active';
  if not found then
    perform wl.fail('NOT_AUTHENTICATED', 'Sessão expirada ou inválida. Entre novamente.', 401);
  end if;
  return p;
end $$;

create or replace function wl.me_admin() returns wl.profiles language plpgsql stable as $$
declare p wl.profiles;
begin
  p := wl.me();
  if p.role <> 'admin' then
    perform wl.fail('FORBIDDEN', 'Acesso reservado a administradores.', 403);
  end if;
  return p;
end $$;

